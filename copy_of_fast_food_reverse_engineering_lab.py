def simulate_meal_customization(
    base_fat,
    base_carb,
    base_protein,
    base_items,
    consumer_weight,
    added_fat=0,
    added_carb=0,
    added_protein=0,
    added_items=0,
):
  """دالة لمحاكاة وتوقع تأثير تعديلات الزبون على الوجبة السريعة

  استناداً إلى معادلات الهندسة العكسية المستخرجة مسبقاً.
  """
  # 1. تحديث الماكروز بعد التعديل
  new_fat = base_fat + added_fat
  new_carb = base_carb + added_carb
  new_protein = base_protein + added_protein
  new_items = base_items + added_items

  # 2. حساب السعرات الكلية الجديدة (بناءً على معادلة الماكروز بدقة 99.9%)
  new_calories = (
      (9.08 * new_fat) + (4.03 * new_carb) + (4.17 * new_protein) - 19.47
  )

  # 3. حساب الصوديوم المتوقع (بناءً على معادلة الصوديوم المستخرجة)
  new_sodium = (
      (1.4132 * new_calories)
      + (1.3119 * new_fat)
      + (0.2353 * new_protein)
      + (0.9930 * new_items)
      + 13.48
  )

  # 4. حساب التأثير الحراري للطعام (TEF)
  new_tef = (0.0738 * new_calories) + 3.34

  # 5. حساب نسبة الدهون المشبعة الجديدة
  new_sat_fat = (0.3949 * new_fat) + 0.37

  # 6. حساب أوقات الحرق الجديدة بناءً على وزن المستهلك والسعرات المحدثة
  walk_time = (0.2186 * new_calories) + (-4.6208 * consumer_weight) + 359.38
  run_time = (0.0736 * new_calories) + (-1.5541 * consumer_weight) + 120.81
  hiit_time = (0.0627 * new_calories) + (-1.3195 * consumer_weight) + 102.68

  # طباعة تقرير المحاكاة بشكل احترافي
  print('==================================================')
  print('          🍔 تقرير محاكاة الوجبة المعدلة          ')
  print('==================================================')
  print(
      f'🔹 إجمالي الدهون: {new_fat:.1f}g (منها مشبعة ضارة:'
      f' {new_sat_fat:.1f}g)'
  )
  print(f'🔹 إجمالي الكربوهيدرات: {new_carb:.1f}g')
  print(f'🔹 إجمالي البروتين: {new_protein:.1f}g')
  print(f'--------------------------------------------------')
  print(f'🔥 السعرات الكلية الجديدة: {new_calories:.1f} kcal')
  print(f'🧂 الصوديوم المتوقع: {new_sodium:.1f} mg')
  print(f'⚡ التأثير الحراري للهضم (TEF): {new_tef:.1f} kcal')
  print('==================================================')
  print('🏃‍♂️ أوقات الحرق المطلوبة لحرق الوجبة المعدلة:')
  print(f'   - وقت المشي (Walking): {max(0, walk_time):.1f} دقيقة')
  print(f'   - وقت الجري (Running): {max(0, run_time):.1f} دقيقة')
  print(f'   - وقت تمارين HIIT: {max(0, hiit_time):.1f} دقيقة')
  print('==================================================\n')


